'use strict';
// ciConfigTransform.js: turns a real config .ini into its secret-free CI copy, line by line.
//
// Shared by buildCiConfig.js (writes the committed copies) and ci-config-names-match.test.js (checks them).
// Kept: section headers, setting names, and only those values that keptValueRuleList.json allows. Dropped: comments.
// Replaced: every other value, by __CI_RANDOM__ (installCiConfig.sh makes each one a fresh random string per run),
// or, for a multi-line quoted value ("... on the following lines ... "), by the rule list's fixed placeholder text.

const fs = require('fs');
const path = require('path');

const ciRandomToken = '__CI_RANDOM__';

const keptValueRulesOf = (ruleListFilePath) => {
	const ruleListText = fs.readFileSync(ruleListFilePath, 'utf8');
	const ruleList = JSON.parse(ruleListText);
	if (!ruleList.sensitiveSettingNamePattern || !Array.isArray(ruleList.keptValueRuleList) || !ruleList.multiLineValuePlaceholderText || !Array.isArray(ruleList.mirroredDirNameList)) {
		throw `ciConfigTransform: ${ruleListFilePath} must give mirroredDirNameList, sensitiveSettingNamePattern, multiLineValuePlaceholderText and keptValueRuleList`;
	}
	return {
		mirroredDirNameList: ruleList.mirroredDirNameList,
		sensitiveSettingNameRegex: new RegExp(ruleList.sensitiveSettingNamePattern, 'i'),
		multiLineValuePlaceholderText: ruleList.multiLineValuePlaceholderText,
		keptValueRuleList: ruleList.keptValueRuleList.map(({ ruleName, pattern }) => ({ ruleName, valueRegex: new RegExp(pattern) })),
	};
};

// [{ entryKind: 'section'|'setting', sectionName, settingName, valueText, isMultiLine }]
const iniEntryListOf = (iniText) => {
	const lineList = iniText.split(/\r?\n/);
	const entryList = [];
	let sectionName = '';
	for (let lineIndex = 0; lineIndex < lineList.length; lineIndex++) {
		const lineText = lineList[lineIndex];
		const trimmedText = lineText.trim();
		if (trimmedText === '' || trimmedText.startsWith(';') || trimmedText.startsWith('#')) {
			continue;
		}
		const sectionMatch = trimmedText.match(/^\[([^\]]+)\]$/);
		if (sectionMatch) {
			sectionName = sectionMatch[1];
			entryList.push({ entryKind: 'section', sectionName });
			continue;
		}
		const equalsIndex = lineText.indexOf('=');
		if (equalsIndex < 1) {
			continue; // a stray line inside no setting; the real parser ignores it too
		}
		const settingName = lineText.slice(0, equalsIndex).trim();
		let valueText = lineText.slice(equalsIndex + 1).trim();
		let isMultiLine = false;
		if (valueText.startsWith('"') && !(valueText.length > 1 && valueText.endsWith('"'))) {
			isMultiLine = true;
			const valueLineList = [valueText];
			while (lineIndex + 1 < lineList.length) {
				lineIndex++;
				valueLineList.push(lineList[lineIndex]);
				if (lineList[lineIndex].trim().endsWith('"')) {
					break;
				}
			}
			valueText = valueLineList.join('\n');
		}
		entryList.push({ entryKind: 'setting', sectionName, settingName, valueText, isMultiLine });
	}
	return entryList;
};

const keptRuleNameOf = ({ settingName, valueText }, keptValueRules) => {
	const isPureSubstitution = /^<![A-Za-z0-9_]+!>$/.test(valueText);
	if (valueText === '' || isPureSubstitution) {
		return valueText === '' ? 'empty' : 'substitutionReference';
	}
	if (keptValueRules.sensitiveSettingNameRegex.test(settingName)) {
		return '';
	}
	const keptRule = keptValueRules.keptValueRuleList.find(({ valueRegex }) => valueRegex.test(valueText));
	return keptRule ? keptRule.ruleName : '';
};

// returns { ciIniText, keptValueList, replacedValueList }
const ciIniTextOf = (realIniText, keptValueRules) => {
	const keptValueList = [];
	const replacedValueList = [];
	const outputLineList = [
		'; CI COPY, generated by server/test/ciConfig/buildCiConfig.js. No real values: see keptValueRuleList.json.',
	];
	iniEntryListOf(realIniText).forEach((iniEntry) => {
		if (iniEntry.entryKind === 'section') {
			outputLineList.push('', `[${iniEntry.sectionName}]`);
			return;
		}
		if (iniEntry.isMultiLine) {
			replacedValueList.push(iniEntry);
			outputLineList.push(`${iniEntry.settingName}="${keptValueRules.multiLineValuePlaceholderText}"`);
			return;
		}
		const keptRuleName = keptRuleNameOf(iniEntry, keptValueRules);
		if (keptRuleName) {
			keptValueList.push({ ...iniEntry, keptRuleName });
			outputLineList.push(`${iniEntry.settingName}=${iniEntry.valueText}`);
			return;
		}
		replacedValueList.push(iniEntry);
		outputLineList.push(`${iniEntry.settingName}=${ciRandomToken}`);
	});
	return { ciIniText: `${outputLineList.join('\n')}\n`, keptValueList, replacedValueList };
};

// section and setting names, as 'section|setting' strings
const iniNameListOf = (iniText) =>
	iniEntryListOf(iniText).map(({ entryKind, sectionName, settingName }) =>
		entryKind === 'section' ? `[${sectionName}]` : `[${sectionName}]|${settingName}`,
	);

// the real .ini files the CI copy mirrors, relative to a configs/instanceSpecific directory
const mirroredIniPathListOf = (instanceSpecificDirPath, mirroredDirNameList) =>
	mirroredDirNameList.flatMap((mirroredDirName) =>
		fs
			.readdirSync(path.join(instanceSpecificDirPath, mirroredDirName))
			.filter((fileName) => fileName.endsWith('.ini'))
			.sort()
			.map((fileName) => path.join(mirroredDirName, fileName)),
	);

// a replaced real value that still appears in the CI text is a leak; a fragment that is itself a section or
// setting name is not (names are copied on purpose)
const leakedSettingListOf = (replacedValueList, allCiText, copiedNameSet) =>
	replacedValueList.filter(({ valueText }) =>
		valueText
			.split('\n')
			.map((lineText) => lineText.trim().replace(/^"|"$/g, ''))
			.filter((fragmentText) => fragmentText.length >= 6 && !copiedNameSet.has(fragmentText))
			.some((fragmentText) => allCiText.includes(fragmentText)),
	);

// the whole CI copy of a real configs/instanceSpecific directory, in memory:
// { builtFileList: [{ relativeIniPath, ciIniText, keptValueList, replacedValueList }], leakList: ['file [section] setting'] }
const ciConfigBuildOf = (sourceInstanceSpecificDirPath, keptValueRules) => {
	const builtFileList = mirroredIniPathListOf(sourceInstanceSpecificDirPath, keptValueRules.mirroredDirNameList).map((relativeIniPath) => ({
		relativeIniPath,
		...ciIniTextOf(fs.readFileSync(path.join(sourceInstanceSpecificDirPath, relativeIniPath), 'utf8'), keptValueRules),
	}));
	const allCiText = builtFileList.map(({ ciIniText }) => ciIniText).join('\n');
	const copiedNameSet = new Set(
		builtFileList.flatMap(({ ciIniText }) => iniEntryListOf(ciIniText).map(({ sectionName, settingName }) => settingName || sectionName)),
	);
	const leakList = builtFileList.flatMap(({ relativeIniPath, replacedValueList }) =>
		leakedSettingListOf(replacedValueList, allCiText, copiedNameSet).map(({ sectionName, settingName }) => `${relativeIniPath} [${sectionName}] ${settingName}`),
	);
	return { builtFileList, leakList };
};

module.exports = { ciRandomToken, keptValueRulesOf, iniEntryListOf, ciIniTextOf, iniNameListOf, mirroredIniPathListOf, ciConfigBuildOf };
